	inline std::vector<std::uint32_t> pbd_pages()
	{
		std::vector<std::uint32_t> result;
		result.reserve(616);
		for (const auto& [begin, end] : pbd_static_ranges)
			for (auto page = begin; page < end; page += 4096)
				result.push_back(page);
		return result;
	}

	template <typename Find>
	bool pbd_requested(Find&& find) noexcept
	{
		const auto is = [&](const char* key, std::string_view expected)
		{
			const auto* value = find(key);
			return value && std::string_view(value) == expected;
		};
		return is("PBD_REPLAY_CONTROLS", "1") &&
		       (is("PBD_REPLAY_TAKEOVER", "fast") ||
				   ((is("PBD_REPLAY_TAKEOVER", "1") || is("PBD_REPLAY_TAKEOVER", "relaunch")) &&
					   is("PBD_REPLAY_TAKEOVER_FAST", "1")));
	}
