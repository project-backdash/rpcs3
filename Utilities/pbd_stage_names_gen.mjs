#!/usr/bin/env node
// Generates rpcs3/Emu/Cell/pbd_stage_names.h from the launcher's game-data/stage-names-v1.json, so the in-game VS cards name a
// stage exactly as the launcher's lobby does. The JSON maps decimal DR stage ids to display names; the launcher shows only names
// matching /^[A-Za-z0-9 '.-]{1,40}$/, and the generator refuses anything else rather than drop it, so the two never disagree.
//
//   node Utilities/pbd_stage_names_gen.mjs <stage-names-v1.json> [<header>]          writes the header
//   node Utilities/pbd_stage_names_gen.mjs <stage-names-v1.json> [<header>] --check  exit 1 when the header differs
//
// The header records the JSON's SHA-256, so a stale table is visible in review. It is written as clang-format leaves
// it, so formatting the tree never makes --check fail.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const check = args.includes('--check');
const paths = args.filter(arg => arg !== '--check');
if (paths.length < 1 || paths.length > 2) {
  console.error('usage: node Utilities/pbd_stage_names_gen.mjs <stage-names-v1.json> [<header>] [--check]');
  process.exit(2);
}
const source = paths[0];
const target = paths[1] ?? fileURLToPath(new URL('../rpcs3/Emu/Cell/pbd_stage_names.h', import.meta.url));

const bytes = readFileSync(source);
const parsed = JSON.parse(bytes.toString('utf8'));
if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) throw new Error('stage names: expected an object');
const maxStageId = 0x25; // the native stage ids a lobby game can apply (pbd::set_channel::max_stage_id)
const entries = Object.entries(parsed).map(([key, name]) => {
  if (!/^(0|[1-9][0-9]*)$/.test(key) || Number(key) > maxStageId) throw new Error(`stage names: bad stage id ${key}`);
  if (typeof name !== 'string' || !/^[A-Za-z0-9 '.-]{1,40}$/.test(name)) throw new Error(`stage names: bad name for stage ${key}`);
  return [Number(key), name];
}).sort((a, b) => a[0] - b[0]);
if (!entries.length) throw new Error('stage names: empty table');

const digest = createHash('sha256').update(bytes).digest('hex');
const rows = entries.map(([id, name]) => `\t\t{${id}, "${name}"},`).join('\n');
const header = `#pragma once

// Generated by Utilities/pbd_stage_names_gen.mjs from the launcher's game-data/stage-names-v1.json
// (SHA-256 ${digest}). Do not edit by hand: change the JSON and run the generator again.

#include <array>
#include <cstdint>
#include <string_view>
#include <utility>

namespace pbd::stage_names
{
	inline constexpr std::string_view source_sha256 = "${digest}";

	// Native stage id (0x1008f088) and its display name, as the launcher's lobby shows it.
	inline constexpr std::array<std::pair<std::uint32_t, std::string_view>, ${entries.length}> names{{
${rows}
	}};

	// The display name of a native stage id, or empty for an id the launcher does not name.
	inline constexpr std::string_view name(std::uint32_t id)
	{
		for (const auto& entry : names)
			if (entry.first == id)
				return entry.second;
		return {};
	}
} // namespace pbd::stage_names
`;

if (check) {
  let current = '';
  try { current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n'); } catch { current = ''; }
  if (current !== header) {
    console.error(`${target} differs from ${source}; run the generator.`);
    process.exit(1);
  }
  console.log(`${target} matches ${source}.`);
} else {
  writeFileSync(target, header);
  console.log(`Wrote ${target} (${entries.length} stages).`);
}
